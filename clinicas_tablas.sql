CREATE TABLE IMAJ_ROLES(
    ID NUMBER,
    NOMBRE_ROL VARCHAR2(16),
    CONSTRAINT PK_IMAJ_ROLES PRIMARY KEY(ID)
);

CREATE TABLE IMAJ_REGIONES(
    ID NUMBER,
    NOMBRE_REGION VARCHAR2(22),
    CONSTRAINT PK_IMAJ_REGIONES PRIMARY KEY(ID)
);

CREATE TABLE IMAJ_USUARIOS(
    ID NUMBER,
    NOMBRE_USUARIO VARCHAR2(16),
    CONTRASEÑA VARCHAR2(255),
    ROL_ID NUMBER,
    CONSTRAINT PK_IMAJ_USUARIOS PRIMARY KEY(ID),
    CONSTRAINT UQ_IMAJ_USUARIOS_NOMBRE UNIQUE(NOMBRE_USUARIO),
    CONSTRAINT FK_IMAJ_USUARIOS_ROLES FOREIGN KEY(ROL_ID)
        REFERENCES IMAJ_ROLES(ID)
);
COMMENT ON COLUMN IMAJ_USUARIOS.CONTRASEÑA IS 'Hash de la contraseña; nunca almacenar texto plano.';

