-- Función utilizada como expresión dentro de SELECT y procedimientos.
-- SELECT INTO asigna el valor de una consulta a una variable.

CREATE OR REPLACE FUNCTION IMAJ_TOTAL_BUDGET(
    P_BUDGET_ID IN NUMBER
) RETURN NUMBER IS
    V_TOTAL NUMBER;
BEGIN
    SELECT NVL(SUM(PRECIO), 0)
    INTO V_TOTAL
    FROM IMAJ_DETALLE_PRESTACIONES
    WHERE PRESUPUESTO_ID = P_BUDGET_ID;

    IF V_TOTAL IS NULL THEN
        RETURN 0;
    ELSE
        RETURN V_TOTAL;
    END IF;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN 0;
END IMAJ_TOTAL_BUDGET;
/

CREATE OR REPLACE FUNCTION IMAJ_AMOUNT_PAID(
    P_BUDGET_ID IN NUMBER
) RETURN NUMBER IS
    V_TOTAL NUMBER;
BEGIN
    SELECT NVL(SUM(MONTO), 0)
    INTO V_TOTAL
    FROM IMAJ_PAGOS
    WHERE PRESUPUESTO_ID = P_BUDGET_ID;

    RETURN V_TOTAL;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN 0;
END IMAJ_AMOUNT_PAID;
/

CREATE OR REPLACE FUNCTION IMAJ_PATIENT_NAME(
    P_PATIENT_ID IN NUMBER
) RETURN VARCHAR2 IS
    V_NAME VARCHAR2(100);
BEGIN
    SELECT NOMBRE || ' ' || APELLIDO_P || ' ' || APELLIDO_M
    INTO V_NAME
    FROM IMAJ_PACIENTES
    WHERE ID = P_PATIENT_ID;

    RETURN V_NAME;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN 'Paciente no encontrado';
END IMAJ_PATIENT_NAME;
/
