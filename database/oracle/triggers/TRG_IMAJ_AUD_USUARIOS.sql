CREATE OR REPLACE TRIGGER TRG_IMAJ_AUD_USUARIOS
AFTER INSERT OR UPDATE OR DELETE ON IMAJ_USUARIOS FOR EACH ROW
DECLARE
    V_ID NUMBER;
    V_OPERATION VARCHAR2(10);
BEGIN
    IF INSERTING THEN V_ID := :NEW.ID; V_OPERATION := 'INSERT';
    ELSIF UPDATING THEN V_ID := :NEW.ID; V_OPERATION := 'UPDATE';
    ELSE V_ID := :OLD.ID; V_OPERATION := 'DELETE';
    END IF;
    INSERT INTO IMAJ_AUDITORIA
        (ID, TABLA, OPERACION, REGISTRO_ID, USUARIO_BD, FECHA_EVENTO)
    VALUES
        (SEQ_IMAJ_AUDITORIA.NEXTVAL, 'IMAJ_USUARIOS', V_OPERATION, V_ID,
         COALESCE(SYS_CONTEXT('USERENV', 'CLIENT_IDENTIFIER'),
                  SYS_CONTEXT('USERENV', 'SESSION_USER')), SYSTIMESTAMP);
END;
/
