CREATE OR REPLACE PROCEDURE IMAJ_BUILD_BUDGET(
    P_ORDER_ID IN NUMBER,
    P_SERVICES IN VARCHAR2
) IS
    V_BUDGET_ID NUMBER;
    V_EXPECTED NUMBER;
    V_INSERTED NUMBER := 0;
BEGIN
    LOCK TABLE IMAJ_PRESUPUESTOS, IMAJ_DETALLE_PRESTACIONES
        IN ROW EXCLUSIVE MODE;

    SELECT COUNT(*)
    INTO V_EXPECTED
    FROM JSON_TABLE(P_SERVICES, '$[*]' COLUMNS (PRESTACION_ID NUMBER PATH '$'));

    IF V_EXPECTED = 0 THEN
        RAISE_APPLICATION_ERROR(-20003, 'El presupuesto requiere al menos una prestación.');
    END IF;

    INSERT INTO IMAJ_PRESUPUESTOS (ID, ESTADO, ORDEN_ID)
    VALUES (SEQ_IMAJ_PRESUPUESTOS.NEXTVAL, 0, P_ORDER_ID);

    V_BUDGET_ID := SEQ_IMAJ_PRESUPUESTOS.CURRVAL;

    FOR ITEM IN (
        SELECT P.ID, P.PRECIO_BASE
        FROM JSON_TABLE(P_SERVICES, '$[*]' COLUMNS (PRESTACION_ID NUMBER PATH '$')) J
        JOIN IMAJ_PRESTACIONES P ON P.ID = J.PRESTACION_ID
        WHERE P.HABILITADA = 1
    ) LOOP
        INSERT INTO IMAJ_DETALLE_PRESTACIONES
            (ID, PRESUPUESTO_ID, PRESTACION_ID, PRECIO)
        VALUES
            (SEQ_IMAJ_DETALLE_PRESTACIONES.NEXTVAL,
             V_BUDGET_ID, ITEM.ID, ITEM.PRECIO_BASE);
        V_INSERTED := V_INSERTED + 1;
    END LOOP;

    IF V_INSERTED <> V_EXPECTED THEN
        RAISE_APPLICATION_ERROR(-20004,
            'Una o más prestaciones no existen o están deshabilitadas.');
    END IF;

    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END IMAJ_BUILD_BUDGET;
/

CREATE OR REPLACE PROCEDURE IMAJ_REGISTER_PAYMENT(
    P_BUDGET_ID IN NUMBER,
    P_AMOUNT IN NUMBER,
    P_METHOD IN VARCHAR2
) IS
    V_PAID NUMBER;
BEGIN
    LOCK TABLE IMAJ_PAGOS, IMAJ_PRESUPUESTOS IN ROW EXCLUSIVE MODE;

    IF P_AMOUNT <= 0 THEN
        RAISE_APPLICATION_ERROR(-20005, 'El monto debe ser mayor que cero.');
    END IF;

    INSERT INTO IMAJ_PAGOS (ID, PRESUPUESTO_ID, MONTO, METODO_PAGO)
    VALUES (SEQ_IMAJ_PAGOS.NEXTVAL, P_BUDGET_ID, P_AMOUNT, P_METHOD);

    SELECT NVL(SUM(MONTO), 0)
    INTO V_PAID
    FROM IMAJ_PAGOS
    WHERE PRESUPUESTO_ID = P_BUDGET_ID;

    UPDATE IMAJ_PRESUPUESTOS
    SET ESTADO = CASE
        WHEN V_PAID >= IMAJ_TOTAL_BUDGET(P_BUDGET_ID) THEN 1
        ELSE 0
    END
    WHERE ID = P_BUDGET_ID;

    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END IMAJ_REGISTER_PAYMENT;
/

CREATE OR REPLACE PROCEDURE IMAJ_COMPLETE_EXAM(
    P_EXAM_ID IN NUMBER,
    P_STATUS IN NUMBER,
    P_COMPLETED IN NUMBER
) IS
    V_ORDER_ID NUMBER;
BEGIN
    LOCK TABLE IMAJ_EXAMENES, IMAJ_ORDENES IN ROW EXCLUSIVE MODE;

    IF P_COMPLETED NOT IN (0, 1) THEN
        RAISE_APPLICATION_ERROR(-20006,
            'El indicador de examen completado debe ser 0 o 1.');
    END IF;

    UPDATE IMAJ_EXAMENES
    SET ESTADO = P_STATUS
    WHERE ID = P_EXAM_ID
    RETURNING ORDEN_ID INTO V_ORDER_ID;

    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20002, 'Examen no encontrado.');
    END IF;

    UPDATE IMAJ_ORDENES
    SET EJECUTADA = P_COMPLETED
    WHERE ID = V_ORDER_ID;

    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END IMAJ_COMPLETE_EXAM;
/

