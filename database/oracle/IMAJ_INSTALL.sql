PROMPT Validando objetos instalados y compilacion PL/SQL...
DECLARE
    V_TABLES PLS_INTEGER;
    V_SUPPORT_TABLES PLS_INTEGER;
    V_SEQUENCES PLS_INTEGER;
    V_FUNCTIONS PLS_INTEGER;
    V_PROCEDURES PLS_INTEGER;
    V_PACKAGES PLS_INTEGER;
    V_PACKAGE_BODIES PLS_INTEGER;
    V_TRIGGERS PLS_INTEGER;
    V_DISABLED_TRIGGERS PLS_INTEGER;
    V_INVALID_OBJECTS PLS_INTEGER := 0;
BEGIN
    SELECT COUNT(*) INTO V_TABLES
    FROM USER_TABLES
    WHERE SUBSTR(TABLE_NAME, 1, 5) = 'IMAJ_';

    SELECT COUNT(*) INTO V_SUPPORT_TABLES
    FROM USER_TABLES
    WHERE UPPER(TABLE_NAME) IN (
        'USERS',
        'PASSWORD_RESET_TOKENS',
        'SESSIONS',
        'CACHE',
        'CACHE_LOCKS',
        'JOBS',
        'JOB_BATCHES',
        'FAILED_JOBS'
    );

    SELECT COUNT(*) INTO V_SEQUENCES
    FROM USER_SEQUENCES
    WHERE SUBSTR(SEQUENCE_NAME, 1, 9) = 'SEQ_IMAJ_';

    SELECT COUNT(*) INTO V_FUNCTIONS
    FROM USER_OBJECTS
    WHERE OBJECT_TYPE = 'FUNCTION'
      AND SUBSTR(OBJECT_NAME, 1, 5) = 'IMAJ_';

    SELECT COUNT(*) INTO V_PROCEDURES
    FROM USER_OBJECTS
    WHERE OBJECT_TYPE = 'PROCEDURE'
      AND SUBSTR(OBJECT_NAME, 1, 5) = 'IMAJ_';

    SELECT COUNT(*) INTO V_PACKAGES
    FROM USER_OBJECTS
    WHERE OBJECT_TYPE = 'PACKAGE'
      AND SUBSTR(OBJECT_NAME, 1, 5) = 'IMAJ_';

    SELECT COUNT(*) INTO V_PACKAGE_BODIES
    FROM USER_OBJECTS
    WHERE OBJECT_TYPE = 'PACKAGE BODY'
      AND SUBSTR(OBJECT_NAME, 1, 5) = 'IMAJ_';

    SELECT COUNT(*) INTO V_TRIGGERS
    FROM USER_TRIGGERS
    WHERE SUBSTR(TRIGGER_NAME, 1, 9) = 'TRG_IMAJ_';

    SELECT COUNT(*) INTO V_DISABLED_TRIGGERS
    FROM USER_TRIGGERS
    WHERE SUBSTR(TRIGGER_NAME, 1, 9) = 'TRG_IMAJ_'
      AND STATUS <> 'ENABLED';

    IF V_TABLES <> 17
       OR V_SUPPORT_TABLES <> 8
       OR V_SEQUENCES <> 17
       OR V_FUNCTIONS <> 3
       OR V_PROCEDURES <> 6
       OR V_PACKAGES <> 3
       OR V_PACKAGE_BODIES <> 3
       OR V_TRIGGERS <> 34
       OR V_DISABLED_TRIGGERS <> 0 THEN
        RAISE_APPLICATION_ERROR(
            -20997,
            'Instalacion incompleta. Tablas=' || V_TABLES ||
            ', tablas de soporte=' || V_SUPPORT_TABLES ||
            ', secuencias=' || V_SEQUENCES ||
            ', funciones=' || V_FUNCTIONS ||
            ', procedimientos=' || V_PROCEDURES ||
            ', paquetes=' || V_PACKAGES ||
            ', cuerpos=' || V_PACKAGE_BODIES ||
            ', triggers=' || V_TRIGGERS ||
            ', triggers deshabilitados=' || V_DISABLED_TRIGGERS || '.'
        );
    END IF;

    FOR OBJ IN (
        SELECT OBJECT_NAME, OBJECT_TYPE
        FROM USER_OBJECTS
        WHERE STATUS = 'INVALID'
          AND (
              SUBSTR(OBJECT_NAME, 1, 5) = 'IMAJ_'
              OR SUBSTR(OBJECT_NAME, 1, 9) IN ('SEQ_IMAJ_', 'TRG_IMAJ_')
          )
        ORDER BY OBJECT_TYPE, OBJECT_NAME
    ) LOOP
        V_INVALID_OBJECTS := V_INVALID_OBJECTS + 1;
        DBMS_OUTPUT.PUT_LINE('Objeto invalido: ' || OBJ.OBJECT_TYPE || ' ' || OBJ.OBJECT_NAME);

        FOR ERR IN (
            SELECT LINE, POSITION, TEXT
            FROM USER_ERRORS
            WHERE NAME = OBJ.OBJECT_NAME
              AND TYPE = OBJ.OBJECT_TYPE
            ORDER BY SEQUENCE
        ) LOOP
            DBMS_OUTPUT.PUT_LINE(
                '  Linea ' || ERR.LINE || ', columna ' || ERR.POSITION || ': ' || ERR.TEXT
            );
        END LOOP;
    END LOOP;

    IF V_INVALID_OBJECTS > 0 THEN
        RAISE_APPLICATION_ERROR(-20996, 'Hay objetos PL/SQL invalidos; revise los errores anteriores.');
    END IF;

    DBMS_OUTPUT.PUT_LINE(
        'Instalacion completa: 17 tablas IMAJ, 8 tablas Laravel, 17 secuencias y 34 triggers activos.'
    );
END;
