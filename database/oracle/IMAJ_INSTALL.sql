CREATE TABLE "USERS" (
    "ID" NUMBER(19, 0) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    "NAME" VARCHAR2(255) NOT NULL,
    "EMAIL" VARCHAR2(255) NOT NULL,
    "EMAIL_VERIFIED_AT" TIMESTAMP NULL,
    "PASSWORD" VARCHAR2(255) NOT NULL,
    "REMEMBER_TOKEN" VARCHAR2(100) NULL,
    "CREATED_AT" TIMESTAMP NULL,
    "UPDATED_AT" TIMESTAMP NULL,
    CONSTRAINT "USERS_ID_PRIMARY" PRIMARY KEY ("ID"),
    CONSTRAINT "USERS_EMAIL_UNIQUE" UNIQUE ("EMAIL")
);

CREATE TABLE "PASSWORD_RESET_TOKENS" (
    "EMAIL" VARCHAR2(255) NOT NULL,
    "TOKEN" VARCHAR2(255) NOT NULL,
    "CREATED_AT" TIMESTAMP NULL,
    CONSTRAINT "PASSWORD_RESET_TOKENS_EMAIL_PRIMARY" PRIMARY KEY ("EMAIL")
);

CREATE TABLE "SESSIONS" (
    "ID" VARCHAR2(255) NOT NULL,
    "USER_ID" NUMBER(19, 0) NULL,
    "IP_ADDRESS" VARCHAR2(45) NULL,
    "USER_AGENT" CLOB NULL,
    "PAYLOAD" CLOB NOT NULL,
    "LAST_ACTIVITY" NUMBER(10, 0) NOT NULL,
    CONSTRAINT "SESSIONS_ID_PRIMARY" PRIMARY KEY ("ID")
);

CREATE INDEX "SESSIONS_USER_ID_INDEX" ON "SESSIONS" ("USER_ID");
CREATE INDEX "SESSIONS_LAST_ACTIVITY_INDEX" ON "SESSIONS" ("LAST_ACTIVITY");

CREATE TABLE "CACHE" (
    "KEY" VARCHAR2(255) NOT NULL,
    "VALUE" CLOB NOT NULL,
    "EXPIRATION" NUMBER(19, 0) NOT NULL,
    CONSTRAINT "CACHE_KEY_PRIMARY" PRIMARY KEY ("KEY")
);

CREATE INDEX "CACHE_EXPIRATION_INDEX" ON "CACHE" ("EXPIRATION");

CREATE TABLE "CACHE_LOCKS" (
    "KEY" VARCHAR2(255) NOT NULL,
    "OWNER" VARCHAR2(255) NOT NULL,
    "EXPIRATION" NUMBER(19, 0) NOT NULL,
    CONSTRAINT "CACHE_LOCKS_KEY_PRIMARY" PRIMARY KEY ("KEY")
);

CREATE INDEX "CACHE_LOCKS_EXPIRATION_INDEX" ON "CACHE_LOCKS" ("EXPIRATION");

CREATE TABLE "JOBS" (
    "ID" NUMBER(19, 0) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    "QUEUE" VARCHAR2(255) NOT NULL,
    "PAYLOAD" CLOB NOT NULL,
    "ATTEMPTS" NUMBER(5, 0) NOT NULL,
    "RESERVED_AT" NUMBER(10, 0) NULL,
    "AVAILABLE_AT" NUMBER(10, 0) NOT NULL,
    "CREATED_AT" NUMBER(10, 0) NOT NULL,
    CONSTRAINT "JOBS_ID_PRIMARY" PRIMARY KEY ("ID")
);

CREATE INDEX "JOBS_QUEUE_INDEX" ON "JOBS" ("QUEUE");

CREATE TABLE "JOB_BATCHES" (
    "ID" VARCHAR2(255) NOT NULL,
    "NAME" VARCHAR2(255) NOT NULL,
    "TOTAL_JOBS" NUMBER(10, 0) NOT NULL,
    "PENDING_JOBS" NUMBER(10, 0) NOT NULL,
    "FAILED_JOBS" NUMBER(10, 0) NOT NULL,
    "FAILED_JOB_IDS" CLOB NOT NULL,
    "OPTIONS" CLOB NULL,
    "CANCELLED_AT" NUMBER(10, 0) NULL,
    "CREATED_AT" NUMBER(10, 0) NOT NULL,
    "FINISHED_AT" NUMBER(10, 0) NULL,
    CONSTRAINT "JOB_BATCHES_ID_PRIMARY" PRIMARY KEY ("ID")
);

CREATE TABLE "FAILED_JOBS" (
    "ID" NUMBER(19, 0) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    "UUID" VARCHAR2(255) NOT NULL,
    "CONNECTION" VARCHAR2(255) NOT NULL,
    "QUEUE" VARCHAR2(255) NOT NULL,
    "PAYLOAD" CLOB NOT NULL,
    "EXCEPTION" CLOB NOT NULL,
    "FAILED_AT" TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT "FAILED_JOBS_ID_PRIMARY" PRIMARY KEY ("ID"),
    CONSTRAINT "FAILED_JOBS_UUID_UNIQUE" UNIQUE ("UUID")
);

CREATE INDEX "FAILED_JOBS_CONNECTION_QUEUE_FAILED_AT_INDEX"
    ON "FAILED_JOBS" ("CONNECTION", "QUEUE", "FAILED_AT");

