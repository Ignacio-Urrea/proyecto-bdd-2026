DECLARE
    V_EXISTING_OBJECTS PLS_INTEGER;
BEGIN
    SELECT COUNT(*)
    INTO V_EXISTING_OBJECTS
    FROM USER_OBJECTS
    WHERE SUBSTR(OBJECT_NAME, 1, 5) = 'IMAJ_'
       OR SUBSTR(OBJECT_NAME, 1, 9) IN ('SEQ_IMAJ_', 'TRG_IMAJ_')
       OR UPPER(OBJECT_NAME) IN (
            'USERS',
            'PASSWORD_RESET_TOKENS',
            'SESSIONS',
            'CACHE',
            'CACHE_LOCKS',
            'JOBS',
            'JOB_BATCHES',
            'FAILED_JOBS'
       );

    IF V_EXISTING_OBJECTS > 0 THEN
        RAISE_APPLICATION_ERROR(
            -20998,
            'El esquema ya contiene objetos IMAJ o de soporte Laravel. Use un esquema Oracle vacio.'
        );
    END IF;
END;
