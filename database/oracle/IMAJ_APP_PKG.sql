                P_TABLE := 'IMAJ_PRESUPUESTOS';
                P_SEQUENCE := 'SEQ_IMAJ_PRESUPUESTOS';
                P_COLUMNS := 'ESTADO, ORDEN_ID';
                P_SELECT_LIST := 'j.ESTADO, j.ORDEN_ID';
