                P_SEQUENCE := 'SEQ_IMAJ_CIUDADES';
                P_COLUMNS := 'REGION_ID, NOMBRE_CIUDAD';
                P_SELECT_LIST := 'j.REGION_ID, j.NOMBRE_CIUDAD';
