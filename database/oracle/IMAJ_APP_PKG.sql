        OPEN P_CURSOR FOR 'SELECT * FROM ' || V_TABLE || ' WHERE ID = :record_id' USING P_ID;
    END FIND_ROW;

    PROCEDURE LIST_ORDER_PRESTATIONS(P_ORDER_ID IN NUMBER, P_CURSOR OUT SYS_REFCURSOR) IS
    BEGIN
        OPEN P_CURSOR FOR
            SELECT P.ID, P.NOMBRE, P.PRECIO_BASE
            FROM IMAJ_ORDENES O
            JOIN IMAJ_SUCURSALES S ON S.ID = O.SUCURSAL_ID
            JOIN IMAJ_PRESTACIONES P ON P.CLINICA_ID = S.CLINICA_ID
            WHERE O.ID = P_ORDER_ID
              AND P.HABILITADA = 1
            ORDER BY P.NOMBRE;
    END LIST_ORDER_PRESTATIONS;

    PROCEDURE INSERT_ROW(P_TABLE IN VARCHAR2, P_PAYLOAD IN CLOB) IS
        V_TABLE VARCHAR2(128);
        V_SEQUENCE VARCHAR2(128);
        V_COLUMNS VARCHAR2(2000);
        V_SELECT_LIST VARCHAR2(4000);
        V_UPDATE_SELECT_LIST VARCHAR2(4000);
        V_JSON_COLUMNS VARCHAR2(4000);
        V_SQL VARCHAR2(32767);
    BEGIN
        SAVEPOINT SP_IMAJ_INSERT_ROW;
        GET_METADATA(P_TABLE, V_TABLE, V_SEQUENCE, V_COLUMNS, V_SELECT_LIST, V_UPDATE_SELECT_LIST, V_JSON_COLUMNS);
        V_SQL := 'INSERT INTO ' || V_TABLE || ' (ID, ' || V_COLUMNS || ') SELECT ' ||
            V_SEQUENCE || '.NEXTVAL, ' || V_SELECT_LIST ||
            ' FROM JSON_TABLE(:payload, ''$'' COLUMNS (' || V_JSON_COLUMNS || ')) j';
        EXECUTE IMMEDIATE V_SQL USING P_PAYLOAD;
    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK TO SP_IMAJ_INSERT_ROW;
            RAISE;
    END INSERT_ROW;

    PROCEDURE UPDATE_ROW(P_TABLE IN VARCHAR2, P_ID IN NUMBER, P_PAYLOAD IN CLOB) IS
        V_TABLE VARCHAR2(128);
        V_SEQUENCE VARCHAR2(128);
        V_COLUMNS VARCHAR2(2000);
        V_SELECT_LIST VARCHAR2(4000);
        V_UPDATE_SELECT_LIST VARCHAR2(4000);
        V_JSON_COLUMNS VARCHAR2(4000);
        V_SQL VARCHAR2(32767);
        V_COLUMN VARCHAR2(128);
        V_INDEX PLS_INTEGER := 1;
    BEGIN
        SAVEPOINT SP_IMAJ_UPDATE_ROW;
        GET_METADATA(P_TABLE, V_TABLE, V_SEQUENCE, V_COLUMNS, V_SELECT_LIST, V_UPDATE_SELECT_LIST, V_JSON_COLUMNS);
        V_UPDATE_SELECT_LIST := NULL;

        LOOP
            V_COLUMN := TRIM(REGEXP_SUBSTR(V_COLUMNS, '[^,]+', 1, V_INDEX));
            EXIT WHEN V_COLUMN IS NULL;

            IF V_INDEX > 1 THEN
                V_UPDATE_SELECT_LIST := V_UPDATE_SELECT_LIST || ', ';
            END IF;

            V_UPDATE_SELECT_LIST := V_UPDATE_SELECT_LIST || 't.' || V_COLUMN || ' = ';

            IF (V_TABLE = 'IMAJ_PACIENTES' AND V_COLUMN = 'FECHA_NACIMIENTO')
                OR (V_TABLE = 'IMAJ_ORDENES' AND V_COLUMN = 'FECHA_CITA')
                OR (V_TABLE = 'IMAJ_EXAMENES' AND V_COLUMN = 'FECHA_SOLICITUD') THEN
                V_UPDATE_SELECT_LIST := V_UPDATE_SELECT_LIST ||
                    'NVL(TO_DATE(j.' || V_COLUMN || ', ''YYYY-MM-DD''), t.' || V_COLUMN || ')';
            ELSE
                V_UPDATE_SELECT_LIST := V_UPDATE_SELECT_LIST ||
                    'NVL(j.' || V_COLUMN || ', t.' || V_COLUMN || ')';
            END IF;

            V_INDEX := V_INDEX + 1;
        END LOOP;

        -- On Oracle XE 21c, the correlated multi-column UPDATE with JSON_TABLE
        -- can keep old values after the first column despite reporting success.
        -- Project the payload once and assign every column from the MERGE source.
        V_SQL := 'MERGE INTO ' || V_TABLE || ' t USING JSON_TABLE(:payload, ''$'' COLUMNS (' ||
            V_JSON_COLUMNS || ')) j ON (t.ID = :record_id) WHEN MATCHED THEN UPDATE SET ' ||
            V_UPDATE_SELECT_LIST;

        EXECUTE IMMEDIATE V_SQL USING P_PAYLOAD, P_ID;

        IF SQL%ROWCOUNT = 0 THEN
            RAISE_APPLICATION_ERROR(-20002, 'Registro no encontrado.');
        END IF;
    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK TO SP_IMAJ_UPDATE_ROW;
            RAISE;
    END UPDATE_ROW;

    PROCEDURE DELETE_ROW(P_TABLE IN VARCHAR2, P_ID IN NUMBER) IS
        V_TABLE VARCHAR2(128);
        V_SEQUENCE VARCHAR2(128);
        V_COLUMNS VARCHAR2(2000);
        V_SELECT_LIST VARCHAR2(4000);
        V_UPDATE_SELECT_LIST VARCHAR2(4000);
        V_JSON_COLUMNS VARCHAR2(4000);
    BEGIN
        SAVEPOINT SP_IMAJ_DELETE_ROW;
        GET_METADATA(P_TABLE, V_TABLE, V_SEQUENCE, V_COLUMNS, V_SELECT_LIST, V_UPDATE_SELECT_LIST, V_JSON_COLUMNS);
        EXECUTE IMMEDIATE 'DELETE FROM ' || V_TABLE || ' WHERE ID = :record_id' USING P_ID;

        IF SQL%ROWCOUNT = 0 THEN
            RAISE_APPLICATION_ERROR(-20002, 'Registro no encontrado.');
        END IF;
    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK TO SP_IMAJ_DELETE_ROW;
            RAISE;
    END DELETE_ROW;

    FUNCTION IMAJ_TOTAL_BUDGET(P_BUDGET_ID IN NUMBER) RETURN NUMBER IS
        V_TOTAL NUMBER;
    BEGIN
        SELECT NVL(SUM(PRECIO), 0)
        INTO V_TOTAL
        FROM IMAJ_DETALLE_PRESTACIONES
        WHERE PRESUPUESTO_ID = P_BUDGET_ID;

        RETURN V_TOTAL;
    END IMAJ_TOTAL_BUDGET;

    FUNCTION IMAJ_AMOUNT_PAID(P_BUDGET_ID IN NUMBER) RETURN NUMBER IS
        V_TOTAL NUMBER;
    BEGIN
        SELECT NVL(SUM(MONTO), 0)
        INTO V_TOTAL
        FROM IMAJ_PAGOS
        WHERE PRESUPUESTO_ID = P_BUDGET_ID;

        RETURN V_TOTAL;
    END IMAJ_AMOUNT_PAID;

    FUNCTION IMAJ_PATIENT_NAME(P_PATIENT_ID IN NUMBER) RETURN VARCHAR2 IS
        V_NAME VARCHAR2(100);
    BEGIN
        SELECT NOMBRE || ' ' || APELLIDO_P || ' ' || APELLIDO_M
        INTO V_NAME
        FROM IMAJ_PACIENTES
        WHERE ID = P_PATIENT_ID;

        RETURN V_NAME;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RETURN NULL;
    END IMAJ_PATIENT_NAME;

    PROCEDURE CREATE_ORDER(
        P_PATIENT_ID IN NUMBER,
        P_BRANCH_ID IN NUMBER,
        P_DATE IN VARCHAR2,
        P_HOUR IN NUMBER
    ) IS
        V_PATIENT_NAME VARCHAR2(100);
    BEGIN
        SAVEPOINT SP_IMAJ_CREATE_ORDER;
        IF P_PATIENT_ID IS NULL OR P_BRANCH_ID IS NULL OR P_DATE IS NULL OR P_HOUR IS NULL THEN
            RAISE_APPLICATION_ERROR(-20008, 'Paciente, sucursal, fecha y hora son obligatorios.');
        END IF;

        V_PATIENT_NAME := IMAJ_PATIENT_NAME(P_PATIENT_ID);
        IF V_PATIENT_NAME IS NULL THEN
            RAISE_APPLICATION_ERROR(-20016, 'El paciente seleccionado no existe.');
        END IF;

        INSERT INTO IMAJ_ORDENES
            (ID, PACIENTE_ID, SUCURSAL_ID, EJECUTADA, FECHA_CITA, HORA_CITA, ESTADO)
        VALUES
            (SEQ_IMAJ_ORDENES.NEXTVAL, P_PATIENT_ID, P_BRANCH_ID, 0,
             TO_DATE(P_DATE, 'YYYY-MM-DD'), P_HOUR, 0);
    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK TO SP_IMAJ_CREATE_ORDER;
            RAISE;
    END CREATE_ORDER;

    PROCEDURE BUILD_BUDGET(P_ORDER_ID IN NUMBER, P_SERVICES IN VARCHAR2) IS
        V_BUDGET_ID NUMBER;
        V_EXPECTED NUMBER;
        V_DISTINCT NUMBER;
        V_INSERTED NUMBER := 0;
        V_CLINICA_ID NUMBER;
        V_SERVICE_ID NUMBER;
        V_SERVICE_PRICE NUMBER;
        CURSOR C_SERVICES(P_CLINIC_ID IN NUMBER) IS
            SELECT P.ID, P.PRECIO_BASE
            FROM JSON_TABLE(P_SERVICES, '$[*]' COLUMNS (PRESTACION_ID NUMBER PATH '$')) J
            JOIN IMAJ_PRESTACIONES P ON P.ID = J.PRESTACION_ID
            WHERE P.CLINICA_ID = P_CLINIC_ID
              AND P.HABILITADA = 1;
    BEGIN
        SAVEPOINT SP_IMAJ_BUILD_BUDGET;
        IF P_ORDER_ID IS NULL THEN
            RAISE_APPLICATION_ERROR(-20009, 'La orden es obligatoria para generar un presupuesto.');
        END IF;

        BEGIN
            SELECT S.CLINICA_ID
            INTO V_CLINICA_ID
            FROM IMAJ_ORDENES O
            JOIN IMAJ_SUCURSALES S ON S.ID = O.SUCURSAL_ID
            WHERE O.ID = P_ORDER_ID;
        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                RAISE_APPLICATION_ERROR(-20012, 'La orden seleccionada no existe.');
        END;

        SELECT COUNT(*), COUNT(DISTINCT PRESTACION_ID)
        INTO V_EXPECTED, V_DISTINCT
        FROM JSON_TABLE(P_SERVICES, '$[*]' COLUMNS (PRESTACION_ID NUMBER PATH '$'));

        IF V_EXPECTED = 0 THEN
            RAISE_APPLICATION_ERROR(-20003, 'El presupuesto requiere al menos una prestación.');
        END IF;

        IF V_EXPECTED <> V_DISTINCT THEN
            RAISE_APPLICATION_ERROR(-20013, 'No se puede incluir la misma prestación más de una vez.');
        END IF;

        INSERT INTO IMAJ_PRESUPUESTOS (ID, ESTADO, ORDEN_ID)
        VALUES (SEQ_IMAJ_PRESUPUESTOS.NEXTVAL, 0, P_ORDER_ID);

        SELECT SEQ_IMAJ_PRESUPUESTOS.CURRVAL INTO V_BUDGET_ID FROM DUAL;

        OPEN C_SERVICES(V_CLINICA_ID);
        LOOP
            FETCH C_SERVICES INTO V_SERVICE_ID, V_SERVICE_PRICE;
            EXIT WHEN C_SERVICES%NOTFOUND;

            INSERT INTO IMAJ_DETALLE_PRESTACIONES
                (ID, PRESUPUESTO_ID, PRESTACION_ID, PRECIO)
            VALUES
                (SEQ_IMAJ_DETALLE_PRESTACIONES.NEXTVAL, V_BUDGET_ID, V_SERVICE_ID, V_SERVICE_PRICE);
            V_INSERTED := V_INSERTED + 1;
        END LOOP;
        CLOSE C_SERVICES;

        IF V_INSERTED <> V_EXPECTED THEN
            RAISE_APPLICATION_ERROR(-20004, 'Una o más prestaciones no existen o están deshabilitadas.');
        END IF;
    EXCEPTION
        WHEN OTHERS THEN
            IF C_SERVICES%ISOPEN THEN
                CLOSE C_SERVICES;
            END IF;
            ROLLBACK TO SP_IMAJ_BUILD_BUDGET;
            RAISE;
    END BUILD_BUDGET;

    PROCEDURE REGISTER_PAYMENT(
        P_BUDGET_ID IN NUMBER,
        P_AMOUNT IN NUMBER,
        P_METHOD IN VARCHAR2
    ) IS
        V_PAID NUMBER;
    BEGIN
        SAVEPOINT SP_IMAJ_REGISTER_PAYMENT;
        IF P_BUDGET_ID IS NULL OR P_METHOD IS NULL OR TRIM(P_METHOD) IS NULL THEN
            RAISE_APPLICATION_ERROR(-20010, 'Presupuesto y método de pago son obligatorios.');
        END IF;

        IF P_AMOUNT IS NULL OR P_AMOUNT <= 0 THEN
            RAISE_APPLICATION_ERROR(-20005, 'El monto debe ser mayor que cero.');
        END IF;

        INSERT INTO IMAJ_PAGOS (ID, PRESUPUESTO_ID, MONTO, METODO_PAGO)
        VALUES (SEQ_IMAJ_PAGOS.NEXTVAL, P_BUDGET_ID, P_AMOUNT, P_METHOD);

        V_PAID := IMAJ_AMOUNT_PAID(P_BUDGET_ID);

        UPDATE IMAJ_PRESUPUESTOS
        SET ESTADO = CASE WHEN V_PAID >= IMAJ_TOTAL_BUDGET(P_BUDGET_ID) THEN 1 ELSE 0 END
        WHERE ID = P_BUDGET_ID;
    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK TO SP_IMAJ_REGISTER_PAYMENT;
            RAISE;
    END REGISTER_PAYMENT;

    PROCEDURE COMPLETE_EXAM(
        P_EXAM_ID IN NUMBER,
        P_STATUS IN NUMBER,
        P_COMPLETED IN NUMBER
    ) IS
        V_ORDER_ID NUMBER;
    BEGIN
        SAVEPOINT SP_IMAJ_COMPLETE_EXAM;
        IF P_EXAM_ID IS NULL OR P_STATUS IS NULL
            OR P_COMPLETED IS NULL OR P_COMPLETED NOT IN (0, 1) THEN
            RAISE_APPLICATION_ERROR(-20006,
                'Examen y estado son obligatorios; el indicador de examen completado debe ser 0 o 1.');
        END IF;

        UPDATE IMAJ_EXAMENES
        SET ESTADO = P_STATUS
        WHERE ID = P_EXAM_ID
        RETURNING ORDEN_ID INTO V_ORDER_ID;

        IF SQL%ROWCOUNT = 0 THEN
            RAISE_APPLICATION_ERROR(-20002, 'Examen no encontrado.');
        END IF;

        UPDATE IMAJ_ORDENES
        SET EJECUTADA = P_COMPLETED
        WHERE ID = V_ORDER_ID;
    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK TO SP_IMAJ_COMPLETE_EXAM;
            RAISE;
    END COMPLETE_EXAM;

    PROCEDURE PUBLISH_REPORT(
        P_EXAM_ID IN NUMBER,
        P_TITLE IN VARCHAR2,
        P_BODY IN VARCHAR2,
        P_ADDENDUM IN NUMBER,
        P_PATH IN VARCHAR2
    ) IS
    BEGIN
        SAVEPOINT SP_IMAJ_PUBLISH_REPORT;
        IF P_EXAM_ID IS NULL OR P_TITLE IS NULL OR TRIM(P_TITLE) IS NULL OR P_BODY IS NULL THEN
            RAISE_APPLICATION_ERROR(-20011, 'Examen, título y contenido del informe son obligatorios.');
        END IF;

        IF P_ADDENDUM IS NULL OR P_ADDENDUM NOT IN (0, 1) THEN
            RAISE_APPLICATION_ERROR(-20007, 'El indicador de adendum debe ser 0 o 1.');
        END IF;

        INSERT INTO IMAJ_INFORMES
            (ID, CUERPO, ADENDUM, TITULO, RUTA, EXAMEN_ID)
        VALUES
            (SEQ_IMAJ_INFORMES.NEXTVAL, P_BODY, P_ADDENDUM, P_TITLE, P_PATH, P_EXAM_ID);
    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK TO SP_IMAJ_PUBLISH_REPORT;
            RAISE;
    END PUBLISH_REPORT;

    PROCEDURE REPORT_ORDERS(P_ALLOWED_IDS IN CLOB, P_CURSOR OUT SYS_REFCURSOR) IS
    BEGIN
        OPEN P_CURSOR FOR
            SELECT S.ID AS SUCURSAL_ID, S.CORREO_SUCURSAL, O.ESTADO, COUNT(*) AS TOTAL_ORDENES
            FROM IMAJ_ORDENES O
            JOIN IMAJ_SUCURSALES S ON S.ID = O.SUCURSAL_ID
            WHERE P_ALLOWED_IDS IS NULL
               OR EXISTS (
                    SELECT 1
                    FROM JSON_TABLE(P_ALLOWED_IDS, '$[*]' COLUMNS (ALLOWED_ID NUMBER PATH '$')) J
                    WHERE J.ALLOWED_ID = O.ID
               )
            GROUP BY S.ID, S.CORREO_SUCURSAL, O.ESTADO
            ORDER BY S.ID, O.ESTADO;
    END REPORT_ORDERS;

    PROCEDURE REPORT_REVENUE(P_ALLOWED_IDS IN CLOB, P_CURSOR OUT SYS_REFCURSOR) IS
    BEGIN
        OPEN P_CURSOR FOR
            SELECT TO_CHAR(A.FECHA_EVENTO, 'YYYY-MM') AS PERIODO,
                   SUM(P.MONTO) AS INGRESOS,
                   COUNT(*) AS TOTAL_PAGOS
            FROM IMAJ_AUDITORIA A
            JOIN IMAJ_PAGOS P ON P.ID = A.REGISTRO_ID
            WHERE A.TABLA = 'IMAJ_PAGOS'
              AND A.OPERACION = 'INSERT'
              AND (
                    P_ALLOWED_IDS IS NULL
                    OR EXISTS (
                        SELECT 1
                        FROM JSON_TABLE(P_ALLOWED_IDS, '$[*]' COLUMNS (ALLOWED_ID NUMBER PATH '$')) J
                        WHERE J.ALLOWED_ID = P.ID
                    )
              )
            GROUP BY TO_CHAR(A.FECHA_EVENTO, 'YYYY-MM')
            ORDER BY PERIODO;
    END REPORT_REVENUE;

    PROCEDURE REPORT_EXAMS(P_ALLOWED_IDS IN CLOB, P_CURSOR OUT SYS_REFCURSOR) IS
    BEGIN
        OPEN P_CURSOR FOR
            SELECT E.URGENCIA, E.ESTADO, COUNT(*) AS TOTAL_EXAMENES
            FROM IMAJ_EXAMENES E
            WHERE P_ALLOWED_IDS IS NULL
               OR EXISTS (
                    SELECT 1
                    FROM JSON_TABLE(P_ALLOWED_IDS, '$[*]' COLUMNS (ALLOWED_ID NUMBER PATH '$')) J
                    WHERE J.ALLOWED_ID = E.ID
               )
            GROUP BY E.URGENCIA, E.ESTADO
            ORDER BY E.URGENCIA, E.ESTADO;
    END REPORT_EXAMS;
