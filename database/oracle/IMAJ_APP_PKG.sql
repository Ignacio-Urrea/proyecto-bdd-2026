            WHEN 'IMAJ_CLINICAS' THEN
                P_TABLE := 'IMAJ_CLINICAS';
                P_SEQUENCE := 'SEQ_IMAJ_CLINICAS';
                P_COLUMNS := 'ADMINISTRADOR_ID, DIRECCION_ID, NOMBRE_CLINICA, CORREO_CLINICA';
                P_SELECT_LIST := 'j.ADMINISTRADOR_ID, j.DIRECCION_ID, j.NOMBRE_CLINICA, j.CORREO_CLINICA';
                P_JSON_COLUMNS := q'[ADMINISTRADOR_ID NUMBER PATH '$.ADMINISTRADOR_ID', DIRECCION_ID NUMBER PATH '$.DIRECCION_ID', NOMBRE_CLINICA VARCHAR2(32) PATH '$.NOMBRE_CLINICA', CORREO_CLINICA VARCHAR2(32) PATH '$.CORREO_CLINICA']';
            WHEN 'IMAJ_SUCURSALES' THEN
                P_TABLE := 'IMAJ_SUCURSALES';
                P_SEQUENCE := 'SEQ_IMAJ_SUCURSALES';
                P_COLUMNS := 'ADMINISTRADOR_ID, CLINICA_ID, CORREO_SUCURSAL, DIRECCION_ID';
                P_SELECT_LIST := 'j.ADMINISTRADOR_ID, j.CLINICA_ID, j.CORREO_SUCURSAL, j.DIRECCION_ID';
                P_JSON_COLUMNS := q'[ADMINISTRADOR_ID NUMBER PATH '$.ADMINISTRADOR_ID', CLINICA_ID NUMBER PATH '$.CLINICA_ID', CORREO_SUCURSAL VARCHAR2(32) PATH '$.CORREO_SUCURSAL', DIRECCION_ID NUMBER PATH '$.DIRECCION_ID']';
