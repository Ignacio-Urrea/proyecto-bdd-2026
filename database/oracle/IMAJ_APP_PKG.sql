CREATE OR REPLACE PACKAGE IMAJ_APP_PKG AS
    PROCEDURE LIST_ROWS(P_TABLE IN VARCHAR2, P_CURSOR OUT SYS_REFCURSOR);
    PROCEDURE FIND_ROW(P_TABLE IN VARCHAR2, P_ID IN NUMBER, P_CURSOR OUT SYS_REFCURSOR);
    PROCEDURE INSERT_ROW(P_TABLE IN VARCHAR2, P_PAYLOAD IN CLOB);
    PROCEDURE UPDATE_ROW(P_TABLE IN VARCHAR2, P_ID IN NUMBER, P_PAYLOAD IN CLOB);
    PROCEDURE DELETE_ROW(P_TABLE IN VARCHAR2, P_ID IN NUMBER);

    PROCEDURE CREATE_ORDER(
        P_PATIENT_ID IN NUMBER,
        P_BRANCH_ID IN NUMBER,
        P_DATE IN VARCHAR2,
        P_HOUR IN NUMBER
    );
    PROCEDURE BUILD_BUDGET(P_ORDER_ID IN NUMBER, P_SERVICES IN VARCHAR2);
    PROCEDURE REGISTER_PAYMENT(
        P_BUDGET_ID IN NUMBER,
        P_AMOUNT IN NUMBER,
        P_METHOD IN VARCHAR2
    );
    PROCEDURE COMPLETE_EXAM(
        P_EXAM_ID IN NUMBER,
        P_STATUS IN NUMBER,
        P_COMPLETED IN NUMBER
    );
    PROCEDURE PUBLISH_REPORT(
        P_EXAM_ID IN NUMBER,
        P_TITLE IN VARCHAR2,
        P_BODY IN VARCHAR2,
        P_ADDENDUM IN NUMBER,
        P_PATH IN VARCHAR2
    );

    PROCEDURE REPORT_ORDERS(P_CURSOR OUT SYS_REFCURSOR);
    PROCEDURE REPORT_REVENUE(P_CURSOR OUT SYS_REFCURSOR);
    PROCEDURE REPORT_EXAMS(P_CURSOR OUT SYS_REFCURSOR);

    FUNCTION TOTAL_BUDGET(P_BUDGET_ID IN NUMBER) RETURN NUMBER;
END IMAJ_APP_PKG;
/

CREATE OR REPLACE PACKAGE BODY IMAJ_APP_PKG AS
    PROCEDURE GET_METADATA(
        P_INPUT IN VARCHAR2,
        P_TABLE OUT VARCHAR2,
        P_SEQUENCE OUT VARCHAR2,
        P_COLUMNS OUT VARCHAR2,
        P_SELECT_LIST OUT VARCHAR2,
        P_UPDATE_SELECT_LIST OUT VARCHAR2,
        P_JSON_COLUMNS OUT VARCHAR2
    ) IS
    BEGIN
        CASE UPPER(TRIM(P_INPUT))
            WHEN 'IMAJ_ROLES' THEN
                P_TABLE := 'IMAJ_ROLES';
                P_SEQUENCE := 'SEQ_IMAJ_ROLES';
                P_COLUMNS := 'NOMBRE_ROL';
                P_SELECT_LIST := 'j.NOMBRE_ROL';
                P_JSON_COLUMNS := q'[NOMBRE_ROL VARCHAR2(16) PATH '$.NOMBRE_ROL']';
            WHEN 'IMAJ_REGIONES' THEN
                P_TABLE := 'IMAJ_REGIONES';
                P_SEQUENCE := 'SEQ_IMAJ_REGIONES';
                P_COLUMNS := 'NOMBRE_REGION';
                P_SELECT_LIST := 'j.NOMBRE_REGION';
                P_JSON_COLUMNS := q'[NOMBRE_REGION VARCHAR2(22) PATH '$.NOMBRE_REGION']';
            WHEN 'IMAJ_PRESTACIONES' THEN
                P_TABLE := 'IMAJ_PRESTACIONES';
                P_SEQUENCE := 'SEQ_IMAJ_PRESTACIONES';
                P_COLUMNS := 'NOMBRE, PRECIO_BASE, HABILITADA';
                P_SELECT_LIST := 'j.NOMBRE, j.PRECIO_BASE, j.HABILITADA';
