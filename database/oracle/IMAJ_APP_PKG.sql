        GET_METADATA(P_TABLE, V_TABLE, V_SEQUENCE, V_COLUMNS, V_SELECT_LIST, V_UPDATE_SELECT_LIST, V_JSON_COLUMNS);
        OPEN P_CURSOR FOR 'SELECT * FROM ' || V_TABLE || ' ORDER BY ID';
    END LIST_ROWS;

    PROCEDURE GET_PAGE_FILTERS(
        P_INPUT IN VARCHAR2,
        P_TABLE OUT VARCHAR2,
        P_FILTERS OUT VARCHAR2
    ) IS
        V_SEQUENCE VARCHAR2(128);
        V_COLUMNS VARCHAR2(2000);
        V_SELECT_LIST VARCHAR2(4000);
        V_UPDATE_SELECT_LIST VARCHAR2(4000);
        V_JSON_COLUMNS VARCHAR2(4000);
    BEGIN
        GET_METADATA(P_INPUT, P_TABLE, V_SEQUENCE, V_COLUMNS, V_SELECT_LIST,
                     V_UPDATE_SELECT_LIST, V_JSON_COLUMNS);

        P_FILTERS := ' WHERE 1 = 1';
        IF P_TABLE = 'IMAJ_ORDENES' THEN
            P_FILTERS := P_FILTERS ||
                ' AND (:date_from IS NULL OR T.FECHA_CITA >= TO_DATE(:date_from, ''YYYY-MM-DD''))' ||
                ' AND (:date_to IS NULL OR T.FECHA_CITA < TO_DATE(:date_to, ''YYYY-MM-DD'') + 1)';
        ELSIF P_TABLE = 'IMAJ_EXAMENES' THEN
            P_FILTERS := P_FILTERS ||
                ' AND (:date_from IS NULL OR T.FECHA_SOLICITUD >= TO_DATE(:date_from, ''YYYY-MM-DD''))' ||
                ' AND (:date_to IS NULL OR T.FECHA_SOLICITUD < TO_DATE(:date_to, ''YYYY-MM-DD'') + 1)';
        END IF;

        P_FILTERS := P_FILTERS ||
            ' AND (:allowed_ids IS NULL OR EXISTS (' ||
            'SELECT 1 FROM JSON_TABLE(:allowed_ids, ''$[*]'' ' ||
            'COLUMNS (ALLOWED_ID NUMBER PATH ''$'')) J WHERE J.ALLOWED_ID = T.ID))';
    END GET_PAGE_FILTERS;

    PROCEDURE LIST_ROWS_PAGE(
        P_TABLE IN VARCHAR2,
        P_DATE_FROM IN VARCHAR2,
        P_DATE_TO IN VARCHAR2,
        P_ALLOWED_IDS IN CLOB,
        P_OFFSET IN NUMBER,
        P_LIMIT IN NUMBER,
        P_CURSOR OUT SYS_REFCURSOR
    ) IS
        V_TABLE VARCHAR2(128);
        V_FILTERS VARCHAR2(4000);
        V_SQL VARCHAR2(32767);
    BEGIN
        IF P_OFFSET IS NULL OR P_OFFSET < 0 OR P_LIMIT IS NULL OR P_LIMIT < 1 OR P_LIMIT > 100 THEN
            RAISE_APPLICATION_ERROR(-20014, 'La paginación debe usar un desplazamiento válido y entre 1 y 100 filas.');
        END IF;

        GET_PAGE_FILTERS(P_TABLE, V_TABLE, V_FILTERS);
        V_SQL := 'SELECT T.*, COUNT(*) OVER() AS TOTAL_COUNT FROM ' || V_TABLE ||
            ' T' || V_FILTERS ||
            ' ORDER BY T.ID OFFSET :row_offset ROWS FETCH NEXT :row_limit ROWS ONLY';

        IF V_TABLE IN ('IMAJ_ORDENES', 'IMAJ_EXAMENES') THEN
            OPEN P_CURSOR FOR V_SQL USING
                P_DATE_FROM, P_DATE_FROM, P_DATE_TO, P_DATE_TO,
                P_ALLOWED_IDS, P_ALLOWED_IDS, P_OFFSET, P_LIMIT;
        ELSE
            OPEN P_CURSOR FOR V_SQL USING
                P_ALLOWED_IDS, P_ALLOWED_IDS, P_OFFSET, P_LIMIT;
        END IF;
    END LIST_ROWS_PAGE;

    PROCEDURE COUNT_ROWS_PAGE(
        P_TABLE IN VARCHAR2,
        P_DATE_FROM IN VARCHAR2,
        P_DATE_TO IN VARCHAR2,
        P_ALLOWED_IDS IN CLOB,
        P_CURSOR OUT SYS_REFCURSOR
    ) IS
        V_TABLE VARCHAR2(128);
        V_FILTERS VARCHAR2(4000);
        V_SQL VARCHAR2(32767);
    BEGIN
        GET_PAGE_FILTERS(P_TABLE, V_TABLE, V_FILTERS);
        V_SQL := 'SELECT COUNT(*) AS TOTAL_COUNT FROM ' || V_TABLE || ' T' || V_FILTERS;

        IF V_TABLE IN ('IMAJ_ORDENES', 'IMAJ_EXAMENES') THEN
            OPEN P_CURSOR FOR V_SQL USING
                P_DATE_FROM, P_DATE_FROM, P_DATE_TO, P_DATE_TO,
                P_ALLOWED_IDS, P_ALLOWED_IDS;
        ELSE
            OPEN P_CURSOR FOR V_SQL USING P_ALLOWED_IDS, P_ALLOWED_IDS;
        END IF;
    END COUNT_ROWS_PAGE;

    PROCEDURE FIND_ROW(P_TABLE IN VARCHAR2, P_ID IN NUMBER, P_CURSOR OUT SYS_REFCURSOR) IS
        V_TABLE VARCHAR2(128);
        V_SEQUENCE VARCHAR2(128);
        V_COLUMNS VARCHAR2(2000);
